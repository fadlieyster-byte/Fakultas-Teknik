// Helper to compute weekly recapitulation summary
export function hitungRekapitulasiMingguanDosen(
  logs: LogPresensiDosen[],
  dosenList: Dosen[],
  mingguKe: number,
  prodiScope: string = 'current',
  selectedProdiId?: string
): RekapMingguanDosen[] {
  // Filter dosen list by prodi scope
  const targetDosens = dosenList.filter(d => {
    if (prodiScope === 'all') return true;
    if (prodiScope === 'current' && selectedProdiId) return d.prodiId === selectedProdiId;
    return d.prodiId === prodiScope;
  });

  return targetDosens.map(dosen => {
    // Find logs for this lecturer in this week
    const dosenLogs = logs.filter(
      l => (l.dosenNidn === dosen.nidn || l.dosenNama === dosen.namaLengkap) && l.mingguKe === mingguKe
    );

    const totalSks = dosen.totalSksMengajar || 12;
    const targetDurasiMenit = totalSks * 50; // Standar SN-Dikti: 1 SKS tatap muka = 50 menit/minggu

    const realisasiDurasiMenit = dosenLogs.reduce((sum, log) => sum + (log.durasiMenit || 0), 0);
    const realisasiDurasiJam = Number((realisasiDurasiMenit / 60).toFixed(2));
    const jumlahKelasTerlaksana = dosenLogs.filter(l => l.statusKehadiran !== 'Ditiadakan').length;
    const jumlahBapTerverifikasi = dosenLogs.filter(l => l.bapStatus === 'Terverifikasi').length;

    // Estimasi jumlah kelas terjadwal per minggu (asumsi rata-rata mata kuliah 2-3 SKS)
    const estimasiKelasTerjadwal = Math.max(dosenLogs.length, Math.ceil(totalSks / 2.5));

    let persenKehadiran = 100;
    if (estimasiKelasTerjadwal > 0) {
      persenKehadiran = Math.min(100, Math.round((jumlahKelasTerlaksana / estimasiKelasTerjadwal) * 100));
    }

    // Status kepatuhan durasi tatap muka BKD
    let statusKepatuhan: RekapMingguanDosen['statusKepatuhan'] = 'Memenuhi Standar BKD';
    if (persenKehadiran >= 95 && realisasiDurasiMenit >= targetDurasiMenit * 0.95) {
      statusKepatuhan = 'Sangat Baik';
    } else if (persenKehadiran >= 80 && realisasiDurasiMenit >= targetDurasiMenit * 0.8) {
      statusKepatuhan = 'Memenuhi Standar BKD';
    } else if (persenKehadiran >= 60) {
      statusKepatuhan = 'Perlu Perhatian';
    } else {
      statusKepatuhan = 'Kurang Jam Mengajar';
    }

    return {
      dosenNidn: dosen.nidn,
      dosenNama: dosen.namaLengkap,
      prodiId: dosen.prodiId,
      jabatanFungsional: dosen.jabatanFungsional,
      totalSksMengajar: totalSks,
      mingguKe,
      targetDurasiMenit,
      realisasiDurasiMenit,
      realisasiDurasiJam,
      persenKehadiran,
      jumlahKelasTerjadwal: estimasiKelasTerjadwal,
      jumlahKelasTerlaksana,
      jumlahBapTerverifikasi,
      statusKepatuhan,
      logs: dosenLogs
    };
  });
}

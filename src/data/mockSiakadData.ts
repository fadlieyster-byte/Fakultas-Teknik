/**
  Aturan Beban SKS Maksimal berdasarkan IPS Semester Sebelumnya di UNBARI:
  - Khusus Semester Pendek (Antara): Maksimal 9 SKS (ketentuan SN-Dikti & Peraturan Akademik UNBARI).
  - Semester Reguler (Ganjil & Genap):
    * IPS >= 3.00       : Maksimal 24 SKS
    * 2.50 <= IPS < 3.00: Maksimal 21 SKS
    * 2.00 <= IPS < 2.50: Maksimal 18 SKS
    * 1.50 <= IPS < 2.00: Maksimal 15 SKS
    * IPS < 1.50        : Maksimal 12 SKS
 */
export function hitungBatasSks(ips: number, tipeSemester: TipeSemester = 'Ganjil'): number {
  if (tipeSemester === 'Pendek') {
    return 9; // Batas maksimal Semester Antara / Pendek
  }
  if (ips >= 3.00) return 24;
  if (ips >= 2.50) return 21;
  if (ips >= 2.00) return 18;
  if (ips >= 1.50) return 15;
  return 12;
}


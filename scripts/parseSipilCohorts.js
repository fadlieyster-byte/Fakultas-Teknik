function parseCohort(raw, angkatan, semester, thnAkademik, baseSks, baseIpk) {
  const lines = raw.trim().split('\n');
  return lines.map((line, idx) => {
    const parts = line.split('\t').map(p => p.trim());
    const nim = parts[0];
    const nama = parts[1];
    const jk = parts[2] || (nama.includes('PUTRI') || nama.includes('SITI') || nama.includes('NUR') || nama.includes('DEWI') ? 'P' : 'L');
    const programStudiRaw = parts[3];
    const jenisRaw = parts[4] || 'REGULER';
    const jenisKelas = jenisRaw.toUpperCase() === 'KARYAWAN' ? 'Karyawan' : 'Reguler';
    const rawStatus = parts[6] ? parts[6].toUpperCase() : 'AKTIF';
    const isAktif = rawStatus.includes('AKTIF') && !rawStatus.includes('NON');
    const status = isAktif ? 'Aktif' : 'Non-Aktif';
    const asalSekolah = parts[7] || '';

    const pa = dosenPA[idx % dosenPA.length];
    const konsentrasi = konsentrasiList[idx % konsentrasiList.length];

    // Calculate realistic IPK & SKS based on status
    const ipk = isAktif 
      ? Number((baseIpk + ((idx * 7) % 70) / 100).toFixed(2))
      : Number((2.10 + ((idx * 5) % 55) / 100).toFixed(2));
    
    const sksLulus = isAktif
      ? baseSks + (idx % 6)
      : Math.max(12, baseSks - 16 - (idx % 10));

    const sksSemesterIni = isAktif ? 20 : 0;
    const kehadiranPersen = isAktif ? (90 + (idx % 11)) : 0;
    const peringatanSp = isAktif ? 0 : ((idx % 2) + 1);

    return {
      id: `MHS-SPL-${nim.slice(-6)}`,
      nim,
      nama,
      prodiId: 'SIPIL',
      programStudi: 'S1 Teknik Sipil FT UNBARI',
      jenjang: 'S1',
      angkatan,
      semester,
      ipk: Math.min(4.00, ipk),
      sksLulus,
      sksSemesterIni,
      sksTargetLulus: 144,
      status,
      dosenPA: pa,
      email: `${nim}@mhs.unbari.ac.id`,
      nomorHp: `0812-72${String(idx).padStart(2, '0')}-${nim.slice(-4)}`,
      kehadiranPersen,
      konsentrasi,
      jenisKelamin: jk,
      jenisKelas,
      asalSekolah: asalSekolah || 'SMA / SMK Sederajat',
      tahunAkademik: thnAkademik,
      peringatanSp
    };
  });
}

